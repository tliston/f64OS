: Z-TOKENIZE ( text-zaddr parse-zaddr dict-zaddr flag -- )
  TO TK-FLAG
  DUP Z-DICT-SETUP TO TK-DICT
  TO TK-PARSE
  TO TK-TEXT
  TK-PARSE Z-B@ TO TK-MAX
  0 TO TK-CNT
  Z-VER 5 >= IF
    2 TO TK-POS
    TK-TEXT 1+ Z-B@ 2 + TO TK-END
  ELSE
    1 TO TK-POS
    1
    BEGIN
      DUP TK-TEXT + Z-B@ 0<>
    WHILE
      1+
    REPEAT
    TO TK-END
  THEN
  BEGIN
    TK-POS TK-END <
  WHILE
    TK-TEXT TK-POS + Z-B@
    DUP 32 = IF
      DROP 1 +TO TK-POS
    ELSE DUP IS-DICT-SEP? IF
      DROP TK-POS 1 TK-ADD-TOKEN
      1 +TO TK-POS
    ELSE
      DROP
      TK-POS TO TK-START
      BEGIN
        TK-POS TK-END < IF
          TK-TEXT TK-POS + Z-B@
          DUP 32 <> SWAP IS-DICT-SEP? NOT AND
        ELSE
          FALSE
        THEN
      WHILE
        1 +TO TK-POS
      REPEAT
      TK-START  TK-POS TK-START -  TK-ADD-TOKEN
    THEN THEN
  REPEAT
  TK-CNT TK-PARSE 1+ Z-B!
;

( --- Line Input [SREAD / AREAD] & Save/Restore ----------------------- )
128 ALLOT CONSTANT IN-LINE-BUF
0 VALUE IN-LEN
0 VALUE IN-MAX

: Z-READ-LINE ( max-len -- len )
  Z-FLUSH-WRAP
  0 TO Z-ROW-COUNT
  TO IN-MAX
  0 TO IN-LEN
  BEGIN
    KEY-RAW
    DUP 10 = OVER 13 = OR IF
      DROP Z-RAW-NL
      IN-LEN EXIT
    THEN
    DUP 8 = OVER 127 = OR IF
      DROP
      IN-LEN 0> IF
        -1 +TO IN-LEN
        8 EMIT
        -1 +TO Z-COL
      THEN
    ELSE DUP 32 127 WITHIN IF
      IN-LEN IN-MAX < IF
        DUP EMIT
        1 +TO Z-COL
        DUP 65 91 WITHIN IF 32 + THEN
        IN-LINE-BUF IN-LEN + C!
        1 +TO IN-LEN
      ELSE
        DROP
      THEN
    ELSE
      DROP
    THEN THEN
  AGAIN
;

